# MIRROR CORE INVARIANT
#
# A voice request does not directly become a real-world action.
#
# It becomes a transaction.
#
# A transaction may be:
# - interpreted
# - forked
# - simulated
# - compared
# - amended
# - committed
# - verified
# - rolled back
#
# Simulation must never mutate live reality.
#
# The model may propose.
# The runtime decides.
# The simulator predicts.
# The user commits.
# The backend executes.
# The verifier determines whether reality matches.
